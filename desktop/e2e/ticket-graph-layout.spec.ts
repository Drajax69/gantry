import { test, expect } from '@playwright/test';
test('large ticket graph fits the dialog and keeps stage controls accessible', async ({ page, request }) => {
  const names = ['Plan', 'Implement', 'Test', 'Create Playwright trace', 'Create PR', 'Review', 'Merge'];
  const graph = { autoStart: false, nodes: names.map((label, i) => ({ id: `step-${i}`, label, kind: 'agent', instructions: `Instructions for ${label}. `.repeat(35), dependsOn: i ? [`step-${i - 1}`] : [] })) };
  expect((await request.post('/api/gantry/api/projects/fixture/workflow', { data: graph })).ok()).toBe(true);
  await request.post('/api/gantry/api/projects/fixture/tickets', { data: { title: 'Large graph layout' } });
  await page.goto('/');
  await page.locator('article').filter({ hasText: 'Large graph layout' }).getByRole('button').first().click();
  const dialog = page.getByRole('dialog');
  expect((await dialog.boundingBox())!.width).toBeGreaterThan(1300);
  const viewport = page.getByLabel('Workflow graph', { exact: true });
  await expect.poll(() => viewport.evaluate(e => e.scrollWidth <= e.clientWidth + 1)).toBe(true);
  await page.getByLabel('Selected workflow stage').selectOption('step-6');
  await expect(page.getByRole('heading', { name: 'Merge', exact: true })).toBeVisible();
  await expect(page.getByText('Instructions for Merge.', { exact: false })).not.toBeVisible();
  await page.getByText('Stage instructions', { exact: true }).click();
  await expect(page.getByText('Instructions for Merge.', { exact: false })).toBeVisible();
  await page.getByText('Stage instructions', { exact: true }).click();
  await page.getByRole('button', { name: 'Zoom in graph' }).click();
  await page.getByRole('button', { name: 'Fit', exact: true }).click();
  await expect.poll(() => viewport.evaluate(e => e.scrollWidth <= e.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: 'e2e/.tmp/ticket-graph-wide.png' });
  await page.setViewportSize({ width: 780, height: 780 });
  await expect.poll(() => viewport.evaluate(e => e.scrollWidth <= e.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: 'e2e/.tmp/ticket-graph-compact.png' });
  expect(await dialog.evaluate(e => e.scrollWidth <= e.clientWidth)).toBe(true);
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
});
